#!/usr/bin/env python3
"""Generate src/data/team.ts from the WordPress team export.

Roles + credentials come from team.csv (scraped from rendered pages — they are
not in the REST API). Bio HTML + names come from team.raw.json. Headshots are
the local files already in public/images/team/<slug>.webp.

Run from the ethos-website directory:  python3 -I scripts/gen-team.py
"""
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
EXPORT = os.path.join(REPO, "..", "arh-agent-docs", "wordpress-export")
OUT = os.path.join(REPO, "src", "data", "team.ts")

# bios keyed by slug
raw = json.load(open(os.path.join(EXPORT, "team.raw.json"), encoding="utf-8"))
bios = {m["slug"]: m["content"]["rendered"].strip() for m in raw}

members = []
with open(os.path.join(EXPORT, "team.csv"), newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        slug = r["slug"].strip()
        members.append(
            {
                "slug": slug,
                "name": r["name"].strip(),
                "role": r["role"].strip(),
                "credentials": r["credentials"].strip(),
                "order": int(r["order"]),
                "photo": f"/images/team/{slug}.webp",
                "excerpt": r["excerpt"].strip(),
                "bioHtml": bios.get(slug, ""),
            }
        )

members.sort(key=lambda m: m["order"])


def js(v):
    return json.dumps(v, ensure_ascii=False)


lines = [
    "// AUTO-GENERATED by scripts/gen-team.py from the WordPress team export.",
    "// Roles/credentials from team.csv; bios from team.raw.json. Do not hand-edit.",
    "",
    "export type TeamMember = {",
    "  slug: string;",
    "  name: string;",
    "  role: string;",
    "  credentials: string;",
    "  order: number;",
    "  photo: string;",
    "  excerpt: string;",
    "  bioHtml: string;",
    "};",
    "",
    "export const team: TeamMember[] = [",
]
for m in members:
    lines.append("  {")
    lines.append(f"    slug: {js(m['slug'])},")
    lines.append(f"    name: {js(m['name'])},")
    lines.append(f"    role: {js(m['role'])},")
    lines.append(f"    credentials: {js(m['credentials'])},")
    lines.append(f"    order: {m['order']},")
    lines.append(f"    photo: {js(m['photo'])},")
    lines.append(f"    excerpt: {js(m['excerpt'])},")
    lines.append(f"    bioHtml: {js(m['bioHtml'])},")
    lines.append("  },")
lines.append("];")
lines.append("")

open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print(f"Wrote {len(members)} team members to {OUT}")
