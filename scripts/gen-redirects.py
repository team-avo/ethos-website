#!/usr/bin/env python3
"""Generate src/data/redirects.ts from the WordPress Redirection export.

Reads arh-agent-docs/wordpress-export/redirects.csv (source,target,code,...)
and emits a typed array consumed by next.config.ts `redirects()`.

Run from the ethos-website directory:  python3 -I scripts/gen-redirects.py
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
CSV = os.path.join(REPO, "..", "arh-agent-docs", "wordpress-export", "redirects.csv")
OUT = os.path.join(REPO, "src", "data", "redirects.ts")

rows = []
with open(CSV, newline="", encoding="utf-8") as f:
    for r in csv.DictReader(f):
        if r.get("enabled", "true").lower() != "true":
            continue
        if r.get("regex", "false").lower() == "true":
            # None in this export; skip if ever present (needs manual handling).
            continue
        src = r["source"].strip()
        dst = r["target"].strip()
        if not src or not dst or src == dst:
            continue
        rows.append((src, dst))

# De-dupe on source, keep first occurrence, preserve order.
seen = set()
unique = []
for src, dst in rows:
    if src in seen:
        continue
    seen.add(src)
    unique.append((src, dst))

lines = [
    "// AUTO-GENERATED by scripts/gen-redirects.py from the WordPress",
    "// Redirection plugin export (wordpress-export/redirects.csv).",
    "// 301s in WordPress; Next emits 308 with `permanent: true`. Do not hand-edit.",
    "",
    "export type Redirect = { source: string; destination: string; permanent: boolean };",
    "",
    "export const legacyRedirects: Redirect[] = [",
]
for src, dst in unique:
    s = src.replace("'", "\\'")
    d = dst.replace("'", "\\'")
    lines.append(f"  {{ source: '{s}', destination: '{d}', permanent: true }},")
lines.append("];")
lines.append("")

with open(OUT, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))

print(f"Wrote {len(unique)} redirects to {OUT}")
